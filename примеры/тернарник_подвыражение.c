// Тернарник в ПРОИЗВОЛЬНОЙ под-позиции (не верхнего уровня декл/return/присв).
// Konda не имеет тернарника-выражения → kfc ХОСТИТ его во временную + если/иначе
// ПЕРЕД оператором, подставляя имя temp на место «?:».
#include <stdio.h>

static int взять2(int усл, int a, int b) {
    return усл ? a : b;                 // верхний уровень return — уже if/иначе
}

static int вычислить(int n) {
    int r = 100 + (n > 5 ? 7 : 3);      // тернарник — ОПЕРАНД «+» → хост
    int s = взять2(n, n > 0 ? 9 : -9, 0);// тернарник — АРГУМЕНТ вызова → хост
    int v = 1 + (n > 0 ? (n > 3 ? 3 : 4) : 5); // ВЛОЖЕННЫЙ тернарник в операнде
    return r + s + v;                   // return-операнд с тернарником (ниже)
}

int main(void) {
    int n = 6;
    printf("%d\n", вычислить(n) + (n > 5 ? 1000 : 0)); // тернарник — аргумент printf
    return 0;
}
