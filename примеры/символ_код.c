/* Код-поинт-арифметика над char (ОЧЕНЬ частое в разборе текста): «c - '0'»
 * (цифра→число), верхний регистр «c - 32». В Konda тип «символ» намеренно
 * НЕарифметичен (§31 — защита char↔int), поэтому такая арифметика доступна
 * только под «небезопасно { }» (§71). Раньше конвертер упирался в ЖЁСТКИЙ
 * барьер («несовместимые типы для «-»») → «// TODO(konda)». Теперь ошибка
 * транспилятора несёт слово «небезопасно», и цикл проверки kfc сам оборачивает
 * оператор: «c - '0'» в теле и в «return» переводятся автоматически. */
#include <stdio.h>

int цифра(char c) {
    return c - '0';                 // return + арифметика символа → temp+небезопасно
}

char в_верхний(char c) {
    if (c >= 'a' && c <= 'z')        // сравнения символов — БЕЗ небезопасно
        return c - 32;               // арифметика → под гейтом
    return c;
}

int main(void) {
    int сумма = цифра('7') + цифра('2');   // 7 + 2 = 9
    char б = в_верхний('k');               // 'K' = 75
    printf("%d %c\n", сумма, б);           // «9 K»
    return 0;
}
