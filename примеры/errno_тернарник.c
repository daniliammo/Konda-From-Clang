// «errno = cond ? a : b» — присваивание в *__errno_location() (небезопасный
// lvalue) с тернарником справа. Конвертер разворачивает тернарник в если/иначе;
// раньше синтезированные присваивания шли БЕЗ «небезопасно», и транспилятор
// отвергал сырое индексирование указателя-результата вызова. Теперь весь
// если/иначе обёрнут в «небезопасно { }» (сырое разыменование за гейтом, P2).
#include <errno.h>

void установить_errno(int код)
{
    errno = код ? код : EINVAL;
}
