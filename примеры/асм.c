/* Вставка ассемблера «__asm__» → «асм(…)» в «небезопасно» (§60 транспилятора).
   Секции C-asm 1:1 совпадают с Konda-«асм», поэтому «(…)»-часть берётся из
   исходника (clang JSON не сериализует шаблон/ограничения/порчу). Шаблоны здесь
   портируемы (пустой шаблон + "r"/"=r"/"0", без арх-инструкций). */
#include <stdio.h>

int main(void) {
    int x = 21;
    int r = 0;
    __asm__ volatile ("" : "=r"(r) : "0"(x));   /* копирует регистр: r = x */
    __asm__ __volatile__("" ::: "memory");       /* компиляторный барьер */
    printf("%d\n", r);
    return 0;
}
