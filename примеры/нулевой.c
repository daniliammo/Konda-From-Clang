// NULL-указатели → «возможно<T*>». В Konda обычный «T*» ненулевой по
// умолчанию; kfc находит указатели, которым C присваивает/возвращает NULL или
// которые сравниваются с NULL, и объявляет их «возможно<T*>»; NULL → «нуль»,
// «if (p)» / «if (!p)» → охранники «!= нуль» / «== нуль», под которыми
// транспилятор сужает nullable до обычного указателя.
#include <stdio.h>

const char *выбрать(int флаг, const char *текст) {
    if (флаг > 0) {
        return текст;
    }
    return NULL;
}

int main(void) {
    const char *есть = выбрать(1, "нашлось");
    const char *нет = выбрать(0, "нашлось");
    if (есть != NULL) {
        printf("1:%s\n", есть);
    }
    if (!нет) {
        printf("2:пусто\n");
    }
    return 0;
}
