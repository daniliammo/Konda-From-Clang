/* Внешняя функция ВОЗВРАЩАЕТ указатель на opaque-тип (opendir → DIR*).
 * Раньше конвертер объявлял «внешний тип DIR», но НЕ сигнатуру opendir, и
 * присваивание «возможно<DIR*> d = opendir(...)» не проходило проверку типов
 * (транспилятор не знал тип результата). Теперь конвертер эмитит прототип
 * «внешняя DIR* opendir(...)» — тип результата известен, присваивание проходит.
 * (Доступ к ПОЛЯМ dirent тут намеренно не трогаем — это отдельный барьер.) */
#include <stdio.h>
#include <dirent.h>

int main(void) {
    DIR *d = opendir(".");
    if (d == NULL) {
        return 1;
    }
    closedir(d);
    printf("открыл и закрыл\n");
    return 0;
}
