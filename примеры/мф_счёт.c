// Многофайловость: функции определены ЗДЕСЬ, а вызываются с «&с» из
// мф_главный.c. При пофайловой конвертации их сигнатуры были бы «чужими»;
// общий граф вызовов проекта позволяет поднять параметры до «изменяемый».
#include "мф_счёт.h"

void счёт_обнулить(Счёт *с) {
    с->значение = 0;
    с->шагов = 0;
}

void счёт_прибавить(Счёт *с, int д) {
    с->значение = с->значение + д;
    с->шагов = с->шагов + 1;
}
