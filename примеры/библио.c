// Внешние прототипы + memset-обнуление. «сдвинуть_на(&х, …)» — вызов
// БИБЛИОТЕЧНОЙ функции (менять её сигнатуру нельзя): kfc объявляет
// «внешняя … (изменяемый целое32 …)» и включает заголовок, а кодоген
// транспилятора сам ставит «&». «memset(&с, 0, sizeof(с))» переводится в
// полевое обнуление без адрес-оф (включая вложенную структуру).
#include <stdio.h>
#include <string.h>
#include "библио.h"

struct Пределы {
    int32_t нижний;
    int32_t верхний;
};

struct Счётчики {
    int32_t годных;
    int32_t битых;
    struct Пределы пределы;
};

int main(void) {
    int32_t х = 10;
    сдвинуть_на(&х, 32);
    struct Счётчики с;
    memset(&с, 0, sizeof(с));
    с.годных = х;
    с.пределы.верхний = 5;
    printf("х=%d годных=%d битых=%d верх=%d\n",
           х, с.годных, с.битых, с.пределы.верхний);
    обнулить_знач(&х);
    printf("сброшено=%d\n", х);
    return 0;
}
