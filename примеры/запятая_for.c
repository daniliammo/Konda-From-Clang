/* Оператор-запятая в for (двухпеременный цикл): «for(int i=0,j=10; i<j; i++,j--)».
 * В Konda заголовок несёт одну init и один шаг → конвертер разбивает: доп.
 * объявление «j=10» ДО цикла, доп. шаг «j--» в конец тела. Результат = C.
 * (Вариант с «continue» получает пометку ПРОВЕРИТЬ — шаг в конце тела он бы
 * пропустил.) */
#include <stdio.h>

int main(void) {
    int sum = 0;
    for (int i = 0, j = 10; i < j; i++, j--) {
        sum += i;
    }
    printf("%d\n", sum);   // 0+1+2+3+4 = 10
    return 0;
}
