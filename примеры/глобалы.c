/* Глобалы, которые kfc переводит в «конст» / помечает:
 *  • структура без C-const, чей адрес уходит только в «const T *» (слушатель
 *    wayland: wl_x_add_listener(obj, &слушатель, data)) — неизменяема → конст;
 *  • предварительное объявление «static const struct X g;» при определении
 *    ниже — печатается одно объявление;
 *  • целый глобал, чей адрес лежит в таблице опций (C пишет через указатель),
 *    — не «атом» (адрес _Atomic несовместим), а пометка «изменяемый-глобал». */
#include <stdio.h>

struct обработчик { int (*вызвать)(int); };

static int удвоить(int x) { return 2 * x; }

static const struct обработчик предварительный;

struct обработчик слушатель = { удвоить };

static int применить(const struct обработчик *о, int x) { return о->вызвать(x); }

static int опция_ширина = 250;
struct опция { const char *имя; int *куда; };
static const struct опция опции[] = { { "ширина", &опция_ширина } };

static const struct обработчик предварительный = { удвоить };

int main(void)
{
	*опции[0].куда = 300;
	printf("%d %d %d\n", применить(&слушатель, 21), применить(&предварительный, 1),
	       опция_ширина);
	return 0;
}
