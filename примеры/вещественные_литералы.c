/* Вещественные литералы (§119 транспилятора: экспонента) и макросы-литералы:
 * «DBL_MAX», «M_PI» печатаются ИМЕНЕМ (объектный макрос, раскрывающийся ровно
 * в один литерал, — по таблице «clang -dM -E»); макрос-выражение и
 * функциональный макрос раскрываются как есть (имя в середину нельзя). */
#include <stdio.h>
#include <float.h>
#include <math.h>
#define ТРЕТЬ (1.0 / 3.0)
#define МАСШТАБ(x) ((x) * 2.5e3)
int main(void)
{
	double большое = DBL_MAX, малое = 1e-9, пи = M_PI, т = ТРЕТЬ, м = МАСШТАБ(2.0);
	float ф = 1.5e3f;
	printf("%g %g %.5f %.4f %.1f %.1f\n", большое, малое, пи, т, м, ф);
	return 0;
}
