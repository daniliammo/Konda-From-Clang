// Транзитивная эвристика владения: указатель ПЕРЕСЫЛАЕТСЯ дальше.
// «шагнуть» сам не пишет в *с — он передаёт с в «прибавить». Раньше это
// блокировало перевод («передаёт p дальше как указатель»); теперь фикспоинт
// видит, что приёмник стал «изменяемый», и вся цепочка легальна:
//   прибавить(изменяемый целое32 с)  ←  шагнуть(изменяемый целое32 с)  ←  &х
#include <stdio.h>

void прибавить(int *с, int д) {
    *с = *с + д;
}

void шагнуть(int *с) {
    прибавить(с, 10);
}

int main(void) {
    int х = 5;
    шагнуть(&х);
    шагнуть(&х);
    прибавить(&х, 1);
    printf("итог=%d\n", х);
    return 0;
}
