/* Двумерный массив «T a[N][M]» → нативный 2D-массив Konda (§55) вместо пометки
 * «многомерный-массив»; три и больше измерений — по-прежнему пометка. */
#include <stdio.h>
int main(void)
{
    int сетка[3][4];
    for (int i = 0; i < 3; i++)
        for (int j = 0; j < 4; j++)
            сетка[i][j] = i * 10 + j;
    float м[2][2] = { { 1.5f, 2.0f }, { 3.0f, 4.5f } };
    printf("%d %d %.1f\n", сетка[2][3], сетка[1][0], м[0][0] + м[1][1]);
    return 0;
}
