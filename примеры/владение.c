/* Типичные C-паттерны мутации через «&x». В Konda оператора «&» нет — kfc
   выводит владение: «T *p» + всюду «f(&x)» → «изменяемый T p» / «вывод T p».
   Кодоген Konda сам ставит «*» в теле и «&» на вызове. */
#include <stdio.h>

/* только ПИШЕТ через указатель → «вывод» (C# out): вызывающему не нужно
   инициализировать переменную заранее */
void заполнить(int *результат) {
    *результат = 42;
}

/* читает И пишет → «изменяемый» (C# ref) */
void удвоить(int *значение) {
    *значение = *значение * 2;
}

/* несколько выходов сразу */
void разделить(int a, int b, int *частное, int *остаток) {
    *частное = a / b;
    *остаток = a % b;
}

/* только читает через указатель → тоже ссылка (иначе был бы «небезопасно») */
int прочитать(int *источник) {
    return *источник + 1;
}

/* структура по указателю */
struct Точка { int x; int y; };
void сдвинуть(struct Точка *т, int дх) {
    т->x = т->x + дх;
}

/* пишет НЕ на всех путях → «вывод» не подойдёт; цикл проверки сам переключит
   догадку на «изменяемый» (транспилятор скажет «не присвоен до возврата») */
void может_не_записать(int *знач, int флаг) {
    if (флаг) { *знач = 99; }
}

int main(void) {
    int r;
    заполнить(&r);
    printf("заполнить=%d\n", r);

    int v = 21;
    удвоить(&v);
    printf("удвоить=%d\n", v);

    int ч, ост;
    разделить(17, 5, &ч, &ост);
    printf("разделить=%d ост=%d\n", ч, ост);

    int и = 9;
    printf("прочитать=%d\n", прочитать(&и));

    struct Точка т = { 1, 2 };
    сдвинуть(&т, 10);
    printf("сдвинуть=%d\n", т.x);

    int м = 7;
    может_не_записать(&м, 0);
    printf("может=%d\n", м);
    return 0;
}
