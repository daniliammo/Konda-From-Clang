/* Локальный указатель-алиас «T *p = &x;». В Konda оператора «&» нет, но такой
   указатель — просто ДРУГОЕ ИМЯ для x: kfc подставляет «x» вместо «p» и вовсе
   опускает объявление. Условие безопасности — каждое упоминание «p» является
   разыменованием (нет переприсваивания/арифметики/передачи). */
#include <stdio.h>

struct Точка { int x; int y; };

int main(void) {
    int x = 5;
    int *p = &x;          /* алиас: p ≡ x */
    printf("чтение=%d\n", p[0]);
    *p = 10;              /* запись через алиас */
    printf("после записи x=%d\n", x);

    struct Точка т = { 1, 2 };
    struct Точка *ук = &т;
    ук->x = ук->x + 100;  /* поле через алиас */
    printf("поле=%d\n", т.x);
    return 0;
}
