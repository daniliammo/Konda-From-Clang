/* Действительно непереводимое: «&x» в вызове ВНЕШНЕЙ функции. Сигнатуру scanf
   менять нельзя, а оператора «&» в Konda нет даже в «небезопасно» — значит
   автоматического перевода не существует. kfc оставляет пометку с вариантами.
   Этот файл НЕ проходит транспилятор — и это ожидаемо. */
#include <stdio.h>

int main(void) {
    int x = 0;
    scanf("%d", &x);      /* ← нет эквивалента: чужая сигнатура + «&» */
    printf("%d\n", x);
    return 0;
}
