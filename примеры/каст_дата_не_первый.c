// void*data-колбэк, где каст «T *x = data» — НЕ первое объявление тела: перед
// ним идёт несвязанная локаль (частый weston-паттерн — «static const double r»
// первой строкой redraw_handler). Детектор A-2 должен пропустить несвязанные
// объявления и всё равно типизировать void*-параметр как «изменяемый T».
// Регистрируется через рамку (как widget_set_*_handler) — без прямого вызова.
#include <stdio.h>

struct точка { int x, y; };
typedef void (*обр_т)(int, void *);

// Внешний регистратор (хранит обработчик; тело в этом файле не нужно).
void установить_обработчик(обр_т h);

static void обработчик(int ширина, void *data)
{
    static const double r = 10.0;      // несвязанная локаль ДО каста
    struct точка *т = data;            // каст на второй строке
    т->x = ширина;
    т->y = (int)r;
}

int main(void)
{
    установить_обработчик(обработчик);
    printf("готово\n");
    return 0;
}
