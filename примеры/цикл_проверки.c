#include <stdio.h>
int хвост(int *a, int n) { return a[n - 1]; }
/* «a» здесь НЕ индексируется — статическая эвристика оставит сырой указатель,
   но вызов передаёт массив → транспилятор возразит, и цикл должен исправить. */
int обёртка(int *a, int n) { return хвост(a, n); }
int main(void) {
    int м[3] = { 10, 20, 30 };
    printf("хвост=%d\n", обёртка(м, 3));
    return 0;
}
