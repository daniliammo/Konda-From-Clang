// goto cleanup, где cleanup-локаль ПЕРВЫМ делом ПРИСВАИВАЕТСЯ (её значение из
// тела функции НЕ нужно): «код = …; … return код». Такая локаль объявляется
// ВНУТРИ хелпера goto_<имя>, а не передаётся параметром. Классический libc-
// паттерн «errsv = errno; … errno = errsv; return -1». Параметр функции,
// читаемый в cleanup (seed), уезжает параметром хелпера как есть.
#include <stdio.h>

int настроить(int seed)
{
    int код;              // присваивается ПЕРВЫМ в cleanup → локаль хелпера
    int итог = 0;

    if (seed < 0)
        goto ошибка;
    if (seed > 100)
        goto ошибка;
    итог = seed * 10;
    return итог;

ошибка:
    код = seed < -50 ? -2 : -1;
    return код;
}

int main(void)
{
    printf("%d %d %d\n", настроить(3), настроить(-5), настроить(-99));
    return 0;
}
