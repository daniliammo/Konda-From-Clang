// Локальная переменная-указатель на функцию «int (*op)(int,int) = add».
// В Konda тип указателя на функцию — именованный «типфункции». Конвертер делает
// пред-проход по телам, синтезирует «типфункции RET ИмяN(типы)» на верхнем
// уровне и эмитит локаль «ИмяN op = add». Присваивание/вызов/переприсваивание —
// как обычно. Результат = C.
#include <stdio.h>

int add(int a, int b) { return a + b; }
int mul(int a, int b) { return a * b; }

int main(void) {
    int (*op)(int, int) = add;
    int r1 = op(10, 20);
    op = mul;                    // переприсваивание другой функцией
    int r2 = op(3, 4);
    printf("%d %d\n", r1, r2);
    return 0;
}
