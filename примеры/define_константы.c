// object-like «#define ИМЯ литерал» — clang их РАЗВОРАЧИВАЕТ до AST, в дереве
// остаются подставленные литералы, макрос как ИМЯ исчезает (пункт C доклада).
// Конвертер ЧАСТИЧНО восстанавливает их из ТЕКСТА исходника: простые числовые
// object-like #define → Konda «конст ИМЯ = литерал» (документирующая
// декларация; использования уже подставлены). Функциональные макросы (§6 в
// Konda нет) и строки/символы — пропускаются.
#include <stdio.h>

#define PI 3.14
#define MAXN 100
#define BYTE_HEX 0xFF
#define GRAV 9.8f
#define MAX(a, b) ((a) > (b) ? (a) : (b))   /* функциональный — пропустить */
#define GREETING "hi"                         /* строка — пропустить */

double площадь(double r) { return PI * r * r; }

int main(void)
{
    // MAX/GREETING определены выше, но НЕ используются здесь — важно лишь, что
    // конвертер не пытается восстановить их как «конст» (функц./строка).
    printf("%.2f %d\n", площадь(2.0), MAXN);
    return 0;
}
