/* «memcpy(D, S, sizeof(T))» объектов одного типа → присваивание объекта
 * (без сырого «&» и байтовой копии). Байтовые копии буферов — не трогаются. */
#include <stdio.h>
#include <string.h>

struct точка { int x, y; };
struct отрезок { struct точка начало, конец; };

static void скопировать_начало(struct отрезок *куда, const struct отрезок *откуда)
{
	memcpy(&куда->начало, &откуда->начало, sizeof(struct точка));
}

int main(void)
{
	struct точка а = { 1, 2 }, б;
	memcpy(&б, &а, sizeof(б));
	struct отрезок о1 = { { 3, 4 }, { 5, 6 } }, о2 = { { 0, 0 }, { 7, 8 } };
	скопировать_начало(&о2, &о1);
	printf("%d %d %d %d %d\n", б.x, б.y, о2.начало.x, о2.начало.y, о2.конец.y);
	return 0;
}
