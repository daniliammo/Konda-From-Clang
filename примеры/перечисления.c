/* Регрессия: анонимный enum → «конст», StaticAssert снимается, локальный
 * (в теле функции) enum выносится на верхний уровень. Раньше всё это давало
 * пометки «проверка-транспилятора». */
#include <stdio.h>

enum { КРАСНЫЙ, ЗЕЛЁНЫЙ = 5, СИНИЙ };        /* анонимный → конст 0/5/6 */

_Static_assert(sizeof(int) >= 4, "нужен 32-битный int");  /* снимается молча */

static int вычислить(void)
{
    enum режим { ЧТЕНИЕ, ЗАПИСЬ };            /* локальный enum → наверх */
    enum режим м = ЗАПИСЬ;
    return (int)м + СИНИЙ;                    /* 1 + 6 = 7 */
}

int main(void)
{
    printf("итог=%d\n", вычислить());
    return 0;
}
