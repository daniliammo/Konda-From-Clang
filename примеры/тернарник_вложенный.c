// Вложенный тернарник: «c1 ? (c2 ? a : b) : d». Раньше внешний тернарник
// понижался в если/иначе, но ВНУТРЕННИЙ (в ветке) падал в тернарник-коммент.
// Теперь понижение рекурсивное — во всех позициях (объявление, присваивание,
// return). Результат = C.
#include <stdio.h>

int classify(int x) {
    return x < 0 ? -1 : (x == 0 ? 0 : 1);   // вложенный тернарник в return
}

int main(void) {
    int a = 5;
    int y = a > 3 ? (a < 10 ? 1 : 2) : 3;   // вложенный в объявлении
    a = a > 3 ? (a > 4 ? 100 : 50) : 0;     // вложенный в присваивании
    printf("%d %d %d %d %d\n", y, a, classify(-2), classify(0), classify(9));
    return 0;
}
