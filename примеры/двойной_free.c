/* Багованный C: одну и ту же память освобождают дважды (double-free, UB).
   Указатель поднимается до «срез<T>» с autofree, лишние free снимаются, поэтому
   перевод РАБОТАЕТ и падать не будет — но kfc помечает место как ПРОВЕРИТЬ,
   чтобы человек/ИИ знал: исходная логика содержала баг. */
#include <stdlib.h>

int main(void) {
    int *p = malloc(4 * sizeof(int));
    p[0] = 7;
    free(p);
    free(p);              /* ← double-free в исходном C */
    return 0;
}
