// Точка входа с argc/argv и колбэком. §36: сигнатура ЕДИНА —
// «целое32 точка_входа(срез<символ*> аргументы)»; argv → «аргументы» (срез,
// argv[0] → аргументы[0]), argc → «длина(аргументы)». argc — производное
// значение, не мутируемая переменная, поэтому мутацию (&x → изменяемый) тестируем
// на локали «счётчик». Колбэк «задать(обработчик)» — имя функции в параметр-
// указатель-на-функцию: kfc синтезирует «типфункции».
#include <stdio.h>
#include "точка_вх.h"

void обработчик(int код) {
    printf("событие %d\n", код);
}

int main(int argc, char **argv) {
    int счётчик = argc;             // argc → длина(аргументы)
    настроить(&счётчик);            // &счётчик → изменяемый (внешняя): *счётчик += 1
    задать(обработчик);             // имя функции → типфункции-параметр
    printf("аргументов: %d\n", счётчик);
    printf("программа: %s\n", argv[0]);   // argv[0] → аргументы[0] (индексация среза)
    return 0;
}
