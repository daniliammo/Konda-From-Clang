// Точка входа с argc/argv и колбэком. Транспилятор жёстко именует параметры
// main как «количество_аргументов»/«аргументы» — kfc переименовывает C-имена
// (argc/argv) и в заголовке, и в теле. Колбэк «задать(обработчик)» — имя
// функции в параметр-указатель-на-функцию: kfc синтезирует «типфункции».
#include <stdio.h>
#include "точка_вх.h"

void обработчик(int код) {
    printf("событие %d\n", код);
}

int main(int argc, char **argv) {
    настроить(&argc, argv);        // &argc → изменяемый (внешняя), argc→количество_аргументов
    задать(обработчик);            // имя функции → типфункции-параметр
    printf("аргументов: %d\n", argc);
    return 0;
}
