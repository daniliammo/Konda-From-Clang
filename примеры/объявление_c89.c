/* C89-стиль: указатели объявлены в начале функции без инициализатора, а
 * присваиваются позже (в т.ч. внутри цикла). Ненулевой указатель Konda без
 * инициализатора не принимает — kfc опускает объявление к первому
 * присваиванию: «T* p = выр» (арифметика указателя — «небезопасно(выр)»). */
#include <stdio.h>

static double сумма_строк(double *данные, int ширина, int высота)
{
	double *строка;
	double итог = 0;
	int x, y;
	for (y = 0; y < высота; y++) {
		строка = данные + y * ширина;
		for (x = 0; x < ширина; x++)
			итог += строка[x];
	}
	return итог;
}

int main(void)
{
	double сетка[6] = { 1, 2, 3, 4, 5, 6 };
	const char *имя;
	имя = "сетка";
	printf("%s %.1f\n", имя, сумма_строк(сетка, 3, 2));
	return 0;
}
