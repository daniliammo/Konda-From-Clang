/* Тернарник в присваивании и НАТИВНЫЕ операторы транспилятора:
 *  • «x = cond ? a : b» → «если (cond) { x = a } иначе { x = b }»
 *    (в Konda нет тернарника-выражения);
 *  • составное присваивание «+= -= <<= …» → нативное (§45), а не «x = x + y»
 *    (цель эмитится один раз, узкие типы не расширяются);
 *  • «x++»/«x--» → нативные (§47), single-eval.
 * Проверяем перевод + совпадение результата с C. */
#include <stdio.h>

int main(void) {
    int x = 3, y = 10;
    x = (y > 5) ? 100 : 200;   // тернарник → если/иначе → x=100
    x += 5;                     // += → 105
    x -= 3;                     // -= → 102
    x <<= 1;                    // <<= → 204
    x++;                        // ++ → 205
    y--;                        // -- → 9
    printf("x=%d y=%d\n", x, y);
    return 0;
}
