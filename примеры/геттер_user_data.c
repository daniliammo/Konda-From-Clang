// void*-возвращающий геттер user-data (window_get_user_data и т.п.): «T *x =
// GETTER(...)» — реинтерпрет void*→T*. Раньше конвертер оборачивал ВСЮ функцию
// в «небезопасно» (сырой указатель живёт за пределами оператора). Теперь (§57)
// эмитим узко: «T* x = небезопасно(как<T*>(GETTER(...)))» — приёмник безопасен
// (member-доступ, передача), функция НЕ уходит в unsafe целиком.
#include <stdio.h>

struct окно;                       // непрозрачный (внешний тип)
struct состояние { int счёт; };

// Внешний геттер: возвращает void* (тип-стёртый user-data).
void *окно_данные(struct окно *w);

static void обновить(struct окно *w) {
    struct состояние *с = окно_данные(w);   // void*→состояние* реинтерпрет
    с->счёт = с->счёт + 1;                   // безопасный member-доступ
    printf("%d\n", с->счёт);
}

int main(void) {
    обновить((struct окно *)0);
    return 0;
}
