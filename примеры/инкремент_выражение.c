/* «++»/«--» ВНУТРИ выражения (в Konda инкремент — только оператор, §47).
 * kfc выносит побочку: префикс — строкой ПЕРЕД оператором, постфикс в простом
 * операторе — ПОСЛЕ, в условии if/return — через temp со старым значением,
 * «while (n--)» — в «пока (истина)» с выносом перед проверкой. */
#include <stdio.h>

static int взять(int *a, int n, int i)
{
    return i < n ? a[i] : -1;
}

static int счётчик(int n)
{
    int k = 0;
    while (n--)
        k += 2;
    return k + n;          /* после цикла n == -1, как в C */
}

static int длина_строки(const char *s)
{
    int n = 0;
    while (*s++)
        n++;
    return n;
}

/* Не вызывается (массив в сырой указатель Konda не передаёт — теряется длина);
 * проверяется ФОРМА перевода: «p[0] = 7» + «p++» и явный «как<T*>(данные)». */
static void заполнить(void *данные)
{
    unsigned int *p = данные;   /* как пиксели в presentation-shm */
    *p++ = 7u;                   /* «p[0] = 7» + «p++» */
    *p++ = 8u;
}

static int после(int *x)
{
    return (*x)++;         /* значение ДО инкремента */
}

int main(void)
{
    int a[8] = {0};
    int i = 0;
    a[i++] = 10;
    a[i++] = 20;
    a[++i] = 40;           /* i: 2 → 3 */
    int j = i++;           /* j = 3, i = 4 */
    int k = 3, всего = 0;
    do {
        всего += k;
    } while (--k);
    int m = 5;
    if (m-- > 4)
        всего += 100;
    int с = i > 3 ? a[j--] : 0;   /* ветвь тернарника с побочкой */
    int z = 1;
    int r = после(&z);
    printf("%d %d %d %d %d %d %d %d %d %d %d %d %d\n",
           a[0], a[1], a[3], i, j, m, всего,
           счётчик(3), длина_строки("абв"), с, взять(a, 8, 1), r, z);
    return 0;
}
