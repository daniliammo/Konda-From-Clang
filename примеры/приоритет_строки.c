/* Регрессии частых паттернов:
 *  • ЯВНЫЕ скобки сохраняются — «(a+b)/c» НЕ должно стать «a+b/c» (мискомпиляция:
 *    развернуть() снимал ParenExpr);
 *  • целочисленные float-литералы «2.0» НЕ должны терять точку (иначе
 *    целочисленное деление: «(a+b)/2.0» = 1.5, а не 1);
 *  • «char s[N] = "..."» → литерал массива символов (транспилятор требует).
 * Результат обязан совпасть с C. */
#include <stdio.h>

int main(void) {
    int a = 1, b = 2, c = 3;
    double avg = (a + b) / 2.0;      // скобки + float-литерал → 1.5
    int r1 = (a + b) * c;            // скобки → 9
    int r2 = a - (b - c);            // скобки → 2
    char msg[8] = "hi";             // char-массив из строки
    printf("%.1f %d %d %s\n", avg, r1, r2, msg);
    return 0;
}
