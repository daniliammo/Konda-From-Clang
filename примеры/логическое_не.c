/* Унарное «!»: в Konda его НЕТ, конвертер понижает:
 *  • «!(сравнение/логика)» → «(… == ложь)»;
 *  • «!целое»              → «(целое == 0)»;
 *  • «!указатель»          → «указатель == нуль» (было и раньше).
 * Проверяем перевод + совпадение с C. */
#include <stdio.h>

int main(void) {
    int a = 5, c = 15, cnt = 0;
    int ok = (a < c) && !(a == c);   // ! на сравнении → == ложь
    int empty = !cnt;                 // ! на целом → == 0
    int both = !(a > c) && !cnt;      // комбинация
    printf("%d %d %d\n", ok, empty, both);
    return 0;
}
