// Вложенная АНОНИМНАЯ структура «struct { int a, b; } inner;» внутри именованной:
// раньше конвертер эмитил бессмысленное «/*функц-тип*/ ничего inner» → доступ
// «n.inner.a» не работал. Теперь пре-проход именует вложенную «Внешняя_поле»,
// поднимает её на верхний уровень как отдельную структуру, поле ссылается на
// новое имя. Инициализация «{1, {2, 3}}» декомпозируется в плоские присваивания
// (транспилятор не принимает нестед struct-литерал в поле). Результат = C.
#include <stdio.h>

typedef struct { int x; struct { int a, b; } inner; } Nested;

int main(void) {
    Nested n = {1, {2, 3}};
    printf("%d %d %d\n", n.x, n.inner.a, n.inner.b);
    return 0;
}
