# -*- coding: utf-8 -*-
"""
Цикл проверки kfc: сгенерировал → прогнал транспилятором → уточнил.

Транспилятор Konda запускается ПОДПРОЦЕССОМ (без линковки libkonda — по
инварианту экосистемы). Он собирает семантические ошибки ПАЧКОЙ за прогон
(«Всего ошибок: N»), поэтому цикл сходится за 2-3 итерации, а не по одной
ошибке за раз.

Идея: начинаем с самого безопасного перевода и ослабляем ТОЛЬКО там, где
транспилятор реально возражает. Так «небезопасно» появляется по факту, а не
по догадке конвертера.

Лестница ослабления (escalation) для одного места:
    1. безопасный перевод (срез/массив)
    2. → «небезопасно { оператор }»            (точечно, один оператор)
    3. → «небезопасно { }» на всё тело функции (если переменная ушла из области)
    4. → пометка KONDA-TODO                     (сдаёмся, объясняем человеку/ИИ)
"""
import os
import re
import shutil
import subprocess
import tempfile

# «Ошибка транспиляции файл.конда (строка 5, колонка 20): текст»
# «Ошибка транспиляции (строка 5, колонка 20): текст»
_ОШИБКА = re.compile(r"Ошибка транспиляции(?:\s+\S+)?\s*\(строка (\d+), колонка (\d+)\):\s*(.*)")


class Диагностика:
    def __init__(self, строка, колонка, текст):
        self.строка, self.колонка, self.текст = int(строка), int(колонка), текст.strip()

    def __repr__(self):
        return f"<{self.строка}:{self.колонка} {self.текст[:50]}>"


def найти_транспилятор(явный=None):
    """Ищет бинарник транспилятора: флаг → env → сосед-проект → PATH."""
    if явный:
        return явный if os.path.exists(явный) else None
    из_среды = os.environ.get("KONDA_ТРАНСПИЛЯТОР")
    if из_среды and os.path.exists(из_среды):
        return из_среды
    здесь = os.path.dirname(os.path.abspath(__file__))
    сосед = os.path.join(здесь, "..", "Транспилятор", "Собранное", "Транспилятор")
    сосед = os.path.normpath(сосед)
    if os.path.exists(сосед):
        return сосед
    return shutil.which("Транспилятор")


def прогнать(транспилятор, текст_конда, имя="проверка"):
    """Транспилирует текст во временном каталоге. → список Диагностик.
    Пустой список = перевод принят транспилятором."""
    with tempfile.TemporaryDirectory() as кат:
        путь = os.path.join(кат, f"{имя}.конда")
        with open(путь, "w", encoding="utf-8") as fh:
            fh.write(текст_конда)
        try:
            п = subprocess.run([транспилятор, f"{имя}.конда"], cwd=кат,
                               capture_output=True, text=True, timeout=120)
        except (subprocess.TimeoutExpired, OSError):
            return [Диагностика(1, 1, "транспилятор не запустился или завис")]
        диаги = []
        for строка in (п.stderr or "").splitlines():
            m = _ОШИБКА.match(строка.strip())
            if m:
                диаги.append(Диагностика(m.group(1), m.group(2), m.group(3)))
        return диаги


# ─── классификация диагностик → действие ──────────────────────────────────────
# Порядок важен: первое совпадение выигрывает.
ПРАВИЛА = [
    # (регулярка по тексту ошибки, действие)
    # — эвристика владения: транспилятор точно знает, ref это или out
    (r"выходной параметр .* не присвоен",       "ссылка:изменяемый"),
    (r"«изменяемый»-аргумент .* должен быть инициализирован", "ссылка:вывод"),
    (r"аргумент для «(вывод|изменяемый)» должен быть переменной", "ссылка:отмена"),
    (r"«конст».*нельзя передать в «(вывод|изменяемый)»", "ссылка:отмена"),
    (r"«изменяемый»/«вывод» не применимы",      "ссылка:отмена"),
    (r"индексация сырого указателя",            "небезопасно"),
    (r"арифметика указателей запрещена",        "небезопасно"),
    (r"реинтерпретаци",                          "небезопасно"),
    (r"член.{0,20}союз|союза",                  "небезопасно"),
    (r"небезопасн",                              "небезопасно"),
    (r"теряет длину|объявите параметр как «срез", "срез_параметр"),
    (r"не объявлена|необъявленн|неизвестн\w+ (переменн|идентификатор)", "полная_обёртка"),
    (r"адрес|«&»",                               "непереводимо:адрес-оф"),
]


def действие_по_ошибке(текст):
    for шаблон, действие in ПРАВИЛА:
        if re.search(шаблон, текст, re.IGNORECASE):
            return действие
    return None
