#!/bin/sh
# Сквозной smoke-тест konda-from-clang.
#   1) C -> .конда через kfc.py (требует clang);
#   2) .конда -> .c -> .elf через транспилятор Konda и проверка вывода.
# Транспилятор ОБЯЗАТЕЛЕН: konda-from-clang генерирует .конда, и без прогона
# через настоящий транспилятор тесты неполны — расхождения синтаксиса (§36/§38
# месяцами ломали for-циклы и main) остаются незамеченными. Поэтому отсутствие
# транспилятора — это ОШИБКА, а не пропуск. Каталог транспилятора берётся из
# переменной окружения KONDA_TRANSPILER (для CI), иначе — соседний каталог.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TR="${KONDA_TRANSPILER:-$ROOT/../ТранспиляторКонда}"
TRBIN="$TR/Собранное/ТранспиляторКонда"
# Экспортируем разрешённый путь, чтобы дочерний kfc.py НАШЁЛ транспилятор для
# своего ЦИКЛА ПРОВЕРКИ где угодно (на CI он лежит в RUNNER_TEMP, не соседом —
# без этого цикл молча выключался, и «вывод» не правился на «изменяемый»).
# kfc принимает и каталог проекта, и путь к бинарнику (проверка.найти_транспилятор).
export KONDA_TRANSPILER="$TR"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Цвет вывода. Включаем, когда это не запрещено (NO_COLOR) и вывод — терминал
# ЛИБО мы на CI (GitHub Actions рендерит ANSI, но TTY там нет → добавляем CI).
# TERM=dumb (например, лог без ANSI) отключает. Коды кладём в переменные через
# printf, чтобы ESC-символ уже был развёрнут (dash echo его не интерпретирует).
if [ -z "${NO_COLOR:-}" ] && [ "${TERM:-}" != dumb ] \
        && { [ -t 1 ] || [ "${CI:-}" = true ]; }; then
    C_H=$(printf '\033[1;36m')      # заголовки секций — голубой жирный
    C_OK=$(printf '\033[32m')       # успех — зелёный
    C_ERR=$(printf '\033[1;31m')    # ошибка — красный жирный
    C_R=$(printf '\033[0m')         # сброс
else
    C_H=''; C_OK=''; C_ERR=''; C_R=''
fi
# sec — печать заголовка секции в цвете (замена «echo "== … =="»).
sec() { printf '%s%s%s\n' "$C_H" "$*" "$C_R"; }

command -v clang >/dev/null 2>&1 || { echo "${C_ERR}ОШИБКА: clang не установлен (обязателен для kfc.py)${C_R}"; exit 1; }
command -v make  >/dev/null 2>&1 || { echo "${C_ERR}ОШИБКА: make не установлен (нужен для сборки транспилятора)${C_R}"; exit 1; }

[ -d "$TR" ] || {
    echo "${C_ERR}ОШИБКА: транспилятор Konda не найден в «$TR».${C_R}"
    echo "  Клонируйте репозиторий рядом с konda-from-clang, либо задайте путь через"
    echo "  переменную окружения KONDA_TRANSPILER=/путь/к/ТранспиляторКонда."
    exit 1
}

# Транспилятор собираем СВЕЖИМ: устаревший бинарник маскирует расхождения
# синтаксиса. Ошибка сборки — фатальна (транспилятор обязателен).
sec "== сборка транспилятора Konda ($TR) =="
make -C "$TR" >/dev/null 2>&1 || {
    echo "${C_ERR}ОШИБКА: не удалось собрать транспилятор Konda в «$TR».${C_R}"
    echo "  Нужен gcc >= 15 или clang >= 19 (полный C23). Попробуйте «make -C \"$TR\" CC=clang»."
    make -C "$TR" 2>&1 | tail -20
    exit 1
}
[ -x "$TRBIN" ] || { echo "${C_ERR}ОШИБКА: транспилятор собран, но бинарник «$TRBIN» отсутствует${C_R}"; exit 1; }
echo "${C_OK}  ок: транспилятор собран${C_R}"

# прогон одного примера: имя, ожидаемая подстрока в выводе .elf
check() {
    name="$1"; want="$2"
    python3 "$ROOT/kfc.py" "$ROOT/примеры/$name.c" -o "$TMP/$name.конда" 2>/dev/null
    echo "  $name: .конда сгенерирован"
    cp "$TMP/$name.конда" "$TR/_smoke_$name.конда"
    # stderr транспилятора (и его внутреннего cc) сохраняем — при провале печатаем,
    # иначе на CI видно лишь «не прошло транспилятор» без причины.
    if ( cd "$TR" && ./Собранное/ТранспиляторКонда "_smoke_$name.конда" >/dev/null 2>"$TMP/$name.trlog" ); then
        out="$("$TR/вывод/_smoke_$name.elf" 2>&1 || true)"
        rm -f "$TR/_smoke_$name.конда"
        echo "$out" | grep -q "$want" || { echo "${C_ERR}    ОШИБКА вывода: нет «$want»${C_R}"; echo "$out"; exit 1; }
        echo "    транспилировано и запущено, вывод содержит «$want»"
    else
        echo "${C_ERR}    ОШИБКА: не прошло транспилятор${C_R}"
        echo "    --- вывод транспилятора: ---"; sed 's/^/    /' "$TMP/$name.trlog"
        echo "    --- сгенерированный .конда: ---"; sed 's/^/    /' "$TR/_smoke_$name.конда"
        # Диагностика: типы узлов инициализаторов из clang JSON AST (спеллинг
        # size_t/long зависит от версии clang → нужно видеть точный qualType).
        if command -v clang >/dev/null 2>&1; then
            echo "    --- типы инициализаторов (clang AST) для $name.c: ---"
            clang -Xclang -ast-dump=json -fsyntax-only "$ROOT/примеры/$name.c" 2>/dev/null \
              | python3 -c '
import json,sys
try: d=json.load(sys.stdin)
except Exception as e: print("    (AST не разобран:",e,")"); sys.exit(0)
def qt(x):
    t=x.get("type")
    return t.get("qualType","") if isinstance(t,dict) else (t or "")
def show(x,ind):
    if not isinstance(x,dict): return
    print("    "+" "*ind+x.get("kind","?")+" "+repr(qt(x))+" "+x.get("castKind",""))
    for c in x.get("inner",[]): show(c,ind+2)
def walk(n):
    if not isinstance(n,dict): return
    if n.get("kind")=="VarDecl":
        print("    VarDecl",n.get("name")); show(n,2)
    for c in n.get("inner",[]): walk(c)
walk(d)' 2>/dev/null || echo "    (диагностика AST не удалась)"
        fi
        rm -f "$TR/_smoke_$name.конда"; exit 1
    fi
}

sec "== базовые управляющие конструкции =="; check demo "больше"
sec "== структуры/enum/switch/malloc/тернарник =="; check богатый "класс=200"
sec "== сырые указатели/срез-параметр/union/reinterpret =="; check указатели "reinterpret=87"
sec "== присваивание в условии while/do/for → вынос в тело =="; check цикл_присваивание "while=10"
sec "== внешняя функция возвращает opaque-указатель (opendir→DIR*) → прототип =="; check внешний_возврат "открыл и закрыл"
sec "== тернарник в присваивании → если/иначе; нативные += / ++ (§45/§47) =="; check операторы_выражений "x=205 y=9"
sec "== скобки-приоритет сохранены + float-литерал «2.0» + char[N]=\"…\" =="; check приоритет_строки "1.5 9 2 hi"
sec "== унарное «!» → «== ложь» (булев) / «== 0» (целое) =="; check логическое_не "1 1 1"
sec "== вложенный тернарник (декл/присв/return) → рекурсивно если/иначе =="; check тернарник_вложенный "1 100 -1 0 1"
sec "== тернарник в ПОД-выражении (операнд/аргумент/индекс) → хост temp+если =="; check тернарник_подвыражение "1120"
sec "== вставка ассемблера «__asm__» → «асм(…)» в «небезопасно» =="; check асм "21"
sec "== realloc-указатель → буфер<T>: malloc→выделить, realloc→перевыделить =="; check буфер_realloc "100"
sec "== nullability-атрибуты: «_Nullable»→возможно<T*>, «_Nonnull»→ссылка =="; check аннотации "77 42"
sec "== конвенция «*_free»/«*_destroy» на срезе → снять (autofree) + ПРОВЕРИТЬ =="; check освобождение "60"
sec "== size_t→int сужение (strlen/sizeof) → как<целое32>, без небезопасно =="; check сужение_каст "5 16 0"
sec "== код-поинт-арифметика символа «c - '0'» → под «небезопасно» (§71), в т.ч. в return =="; check символ_код "9 K"
sec "== оператор-запятая в for → разбить (доп. объявление до, доп. шаг в конец) =="; check запятая_for "10"
sec "== локаль-указатель на функцию → синтез типфункции =="; check указатель_функции_локаль "30 12"
sec "== вложенная АНОНИМНАЯ структура → поднять как Внешняя_поле + плоский init =="; check вложенный_аноним "1 2 3"

sec "== эвристика владения: «f(&x)» → «изменяемый»/«вывод», без пометок =="
if [ -x "$TRBIN" ]; then
    python3 "$ROOT/kfc.py" "$ROOT/примеры/владение.c" -o "$TMP/в.конда" 2>"$TMP/в.log"
    # Цикл проверки ОБЯЗАН отработать (транспилятор найден): «без проверки» в итоге
    # означало бы, что kfc не нашёл транспилятор и догадки не проверены — то есть
    # тест ниже про «вывод→изменяемый» бессмысленен. Валимся явно.
    grep -q "принят транспилятором" "$TMP/в.log" \
        || { echo "${C_ERR}  ОШИБКА: цикл проверки НЕ отработал (kfc не нашёл транспилятор?)${C_R}"; cat "$TMP/в.log"; exit 1; }
    grep -q "пометок: 0" "$TMP/в.log" \
        || { echo "${C_ERR}  ОШИБКА: ожидался перевод без пометок${C_R}"; cat "$TMP/в.log"; exit 1; }
    grep -q "заполнить(вывод целое32" "$TMP/в.конда" \
        || { echo "${C_ERR}  ОШИБКА: запись-только должна давать «вывод»${C_R}"; exit 1; }
    grep -q "удвоить(изменяемый целое32" "$TMP/в.конда" \
        || { echo "${C_ERR}  ОШИБКА: чтение+запись должны давать «изменяемый»${C_R}"; exit 1; }
    grep -q "сдвинуть(изменяемый Точка" "$TMP/в.конда" \
        || { echo "${C_ERR}  ОШИБКА: «p->поле» должно давать «изменяемый»${C_R}"; exit 1; }
    # цикл обязан исправить догадку «вывод»→«изменяемый» (запись не на всех путях)
    grep -q "может_не_записать(изменяемый целое32" "$TMP/в.конда" \
        || { echo "${C_ERR}  ОШИБКА: цикл не исправил «вывод» на «изменяемый»${C_R}"; exit 1; }
    grep -q '"/\*&\*/"' "$TMP/в.конда" && { echo "${C_ERR}  ОШИБКА: остался сырой «&»${C_R}"; exit 1; }
    echo "${C_OK}  ок: вывод/изменяемый выведены, «&» снят, цикл исправил догадку${C_R}"
fi
check владение "сдвинуть=11"

sec "== nullability-атрибуты: сигнатуры возможно<T*> / ненулевая ссылка =="
python3 "$ROOT/kfc.py" --без-проверки "$ROOT/примеры/аннотации.c" \
    -o "$TMP/ann.конда" 2>/dev/null
grep -q "первый_или(возможно<целое32\*> p" "$TMP/ann.конда" \
    || { echo "${C_ERR}  ОШИБКА: «_Nullable» → возможно<T*> (не ссылка)${C_R}"; \
         grep первый_или "$TMP/ann.конда"; exit 1; }
grep -q "удвой(изменяемый целое32 q)" "$TMP/ann.конда" \
    || { echo "${C_ERR}  ОШИБКА: «_Nonnull» → ненулевая ссылка${C_R}"; \
         grep удвой "$TMP/ann.конда"; exit 1; }
echo "${C_OK}  ок: «_Nullable»→возможно<T*> (не изменяемый), «_Nonnull»→ссылка${C_R}"

sec "== локальный указатель «T *p = &x» подставляется как «x» =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/локальный_указатель.c" -o "$TMP/лу.конда" 2>"$TMP/лу.log"
grep -q "пометок: 0" "$TMP/лу.log" \
    || { echo "${C_ERR}  ОШИБКА: ожидалось 0 пометок${C_R}"; cat "$TMP/лу.log"; exit 1; }
grep -q "целое32\* p" "$TMP/лу.конда" && { echo "${C_ERR}  ОШИБКА: указатель не убран${C_R}"; exit 1; }
grep -q "KONDA-TODO" "$TMP/лу.конда" && { echo "${C_ERR}  ОШИБКА: остались пометки${C_R}"; exit 1; }
echo "${C_OK}  ок: алиас подставлен, объявление убрано, пометок нет${C_R}"
check локальный_указатель "поле=101"

sec "== багованный C: double-free → ПРОВЕРИТЬ, но перевод работает =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/двойной_free.c" -o "$TMP/дф.конда" 2>"$TMP/дф.log"
grep -q "KONDA-TODO\[ПРОВЕРИТЬ\] в C-исходнике похоже на двойной free" "$TMP/дф.конда" \
    || { echo "${C_ERR}  ОШИБКА: double-free не помечен${C_R}"; cat "$TMP/дф.конда"; exit 1; }
grep -qc "выделить(4)" "$TMP/дф.конда" \
    || { echo "${C_ERR}  ОШИБКА: malloc не стал «выделить»${C_R}"; exit 1; }
grep -vE "^\s*//" "$TMP/дф.конда" | grep -q "free(" \
    && { echo "${C_ERR}  ОШИБКА: вызов free должен быть снят (autofree)${C_R}"; exit 1; }
echo "${C_OK}  ок: лишний free снят, место помечено ПРОВЕРИТЬ, перевод компилируем${C_R}"

sec "== по-настоящему непереводимое (&x во внешний scanf) =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/непереводимое.c" --без-проверки 2>/dev/null \
    | grep -q "KONDA-TODO\[НЕПЕРЕВОДИМО\]" \
    && echo "${C_OK}  ок: помечено KONDA-TODO[НЕПЕРЕВОДИМО]${C_R}" \
    || { echo "${C_ERR}  ОШИБКА: не помечено${C_R}"; exit 1; }

if [ -x "$TRBIN" ]; then
    sec "== цикл проверки чинит то, что эвристика пропустила =="
    # «обёртка» не индексирует свой параметр → эвристика оставит сырой указатель,
    # но вызов передаёт массив. Цикл обязан поднять параметр до «срез<T>».
    python3 "$ROOT/kfc.py" "$ROOT/примеры/цикл_проверки.c" --без-проверки 2>/dev/null \
        | grep -q "обёртка(целое32\* a" \
        || { echo "${C_ERR}  ОШИБКА: ожидался сырой указатель без цикла${C_R}"; exit 1; }
    python3 "$ROOT/kfc.py" "$ROOT/примеры/цикл_проверки.c" -o "$TMP/ц.конда" 2>/dev/null
    grep -q "обёртка(срез<целое32> a" "$TMP/ц.конда" \
        && echo "${C_OK}  ок: цикл поднял параметр «обёртка» до «срез<целое32>»${C_R}" \
        || { echo "${C_ERR}  ОШИБКА: цикл не исправил параметр${C_R}"; cat "$TMP/ц.конда"; exit 1; }
    check цикл_проверки "хвост=30"

    sec "== цикл проверки: вердикт «принят транспилятором» =="
    python3 "$ROOT/kfc.py" "$ROOT/примеры/указатели.c" -o "$TMP/у.конда" 2>&1 \
        | grep -q "принят транспилятором" \
        && echo "${C_OK}  ок: цикл подтвердил перевод у транспилятора${C_R}" \
        || { echo "${C_ERR}  ОШИБКА: цикл не подтвердил перевод${C_R}"; exit 1; }

    sec "== вердикт честен: закомментированное меняет поведение =="
    python3 "$ROOT/kfc.py" "$ROOT/примеры/непереводимое.c" -o "$TMP/а.конда" \
        --отчёт "$TMP/а.json" 2>"$TMP/а.log" || true
    grep -q "поведение изменено" "$TMP/а.log" \
        && echo "${C_OK}  ок: не выдаём «принят», раз фрагмент закомментирован${C_R}" \
        || { echo "${C_ERR}  ОШИБКА: вердикт вводит в заблуждение${C_R}"; cat "$TMP/а.log"; exit 1; }

    sec "== JSON-отчёт для ИИ =="
    python3 - "$TMP/а.json" <<'PY' || exit 1
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
assert d["всего"] >= 1, "ожидались задачи в отчёте"
assert d["блокирует_компиляцию"] >= 1, "ожидалась блокирующая задача"
z = d["задачи"][0]
for поле in ("файл", "строка", "категория", "код", "причина", "варианты",
             "c_исходник", "блокирует_компиляцию"):
    assert поле in z, f"нет поля {поле}"
assert z["варианты"], "у задачи должны быть варианты решения"
assert z["c_исходник"], "должен быть исходный код C"
print("  ок: отчёт содержит задачи с вариантами и C-исходником")
PY
fi

