#!/bin/sh
# Сквозной smoke-тест konda-from-clang.
#   1) C -> .конда через kfc.py (требует clang);
#   2) если рядом транспилятор Konda — .конда -> .c -> .elf и проверка вывода.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TR="$ROOT/../ТранспиляторКонда"
TRBIN="$TR/Собранное/ТранспиляторКонда"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

command -v clang >/dev/null 2>&1 || { echo "ПРОПУСК: clang не установлен"; exit 0; }

# Транспилятор собираем СВЕЖИМ: тесты гоняют .конда через готовый бинарник, и
# устаревший бинарник маскирует расхождения синтаксиса (так §36/§38 месяцами
# ломали for-циклы и main незаметно). Если каталог рядом и есть make — пересобрать.
if [ -d "$TR" ] && command -v make >/dev/null 2>&1; then
    make -C "$TR" >/dev/null 2>&1 \
        || echo "ВНИМАНИЕ: не удалось пересобрать транспилятор — тест идёт на текущем бинарнике"
fi

# прогон одного примера: имя, ожидаемая подстрока в выводе .elf
check() {
    name="$1"; want="$2"
    python3 "$ROOT/kfc.py" "$ROOT/примеры/$name.c" -o "$TMP/$name.конда" 2>/dev/null
    echo "  $name: .конда сгенерирован"
    [ -x "$TRBIN" ] || { echo "    (пропуск транспиляции: нет $TRBIN)"; return 0; }
    cp "$TMP/$name.конда" "$TR/_smoke_$name.конда"
    if ( cd "$TR" && ./Собранное/ТранспиляторКонда "_smoke_$name.конда" >/dev/null 2>&1 ); then
        out="$("$TR/вывод/_smoke_$name.elf" 2>&1 || true)"
        rm -f "$TR/_smoke_$name.конда"
        echo "$out" | grep -q "$want" || { echo "    ОШИБКА вывода: нет «$want»"; echo "$out"; exit 1; }
        echo "    транспилировано и запущено, вывод содержит «$want»"
    else
        rm -f "$TR/_smoke_$name.конда"
        echo "    ОШИБКА: не прошло транспилятор"; exit 1
    fi
}

echo "== базовые управляющие конструкции =="; check demo "больше"
echo "== структуры/enum/switch/malloc/тернарник =="; check богатый "класс=200"
echo "== сырые указатели/срез-параметр/union/reinterpret =="; check указатели "reinterpret=87"
echo "== присваивание в условии while/do/for → вынос в тело =="; check цикл_присваивание "while=10"
echo "== внешняя функция возвращает opaque-указатель (opendir→DIR*) → прототип =="; check внешний_возврат "открыл и закрыл"
echo "== тернарник в присваивании → если/иначе; нативные += / ++ (§45/§47) =="; check операторы_выражений "x=205 y=9"
echo "== скобки-приоритет сохранены + float-литерал «2.0» + char[N]=\"…\" =="; check приоритет_строки "1.5 9 2 hi"

echo "== эвристика владения: «f(&x)» → «изменяемый»/«вывод», без пометок =="
if [ -x "$TRBIN" ]; then
    python3 "$ROOT/kfc.py" "$ROOT/примеры/владение.c" -o "$TMP/в.конда" 2>"$TMP/в.log"
    grep -q "пометок: 0" "$TMP/в.log" \
        || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/в.log"; exit 1; }
    grep -q "заполнить(вывод целое32" "$TMP/в.конда" \
        || { echo "  ОШИБКА: запись-только должна давать «вывод»"; exit 1; }
    grep -q "удвоить(изменяемый целое32" "$TMP/в.конда" \
        || { echo "  ОШИБКА: чтение+запись должны давать «изменяемый»"; exit 1; }
    grep -q "сдвинуть(изменяемый Точка" "$TMP/в.конда" \
        || { echo "  ОШИБКА: «p->поле» должно давать «изменяемый»"; exit 1; }
    # цикл обязан исправить догадку «вывод»→«изменяемый» (запись не на всех путях)
    grep -q "может_не_записать(изменяемый целое32" "$TMP/в.конда" \
        || { echo "  ОШИБКА: цикл не исправил «вывод» на «изменяемый»"; exit 1; }
    grep -q '"/\*&\*/"' "$TMP/в.конда" && { echo "  ОШИБКА: остался сырой «&»"; exit 1; }
    echo "  ок: вывод/изменяемый выведены, «&» снят, цикл исправил догадку"
fi
check владение "сдвинуть=11"

echo "== локальный указатель «T *p = &x» подставляется как «x» =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/локальный_указатель.c" -o "$TMP/лу.конда" 2>"$TMP/лу.log"
grep -q "пометок: 0" "$TMP/лу.log" \
    || { echo "  ОШИБКА: ожидалось 0 пометок"; cat "$TMP/лу.log"; exit 1; }
grep -q "целое32\* p" "$TMP/лу.конда" && { echo "  ОШИБКА: указатель не убран"; exit 1; }
grep -q "KONDA-TODO" "$TMP/лу.конда" && { echo "  ОШИБКА: остались пометки"; exit 1; }
echo "  ок: алиас подставлен, объявление убрано, пометок нет"
check локальный_указатель "поле=101"

echo "== багованный C: double-free → ПРОВЕРИТЬ, но перевод работает =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/двойной_free.c" -o "$TMP/дф.конда" 2>"$TMP/дф.log"
grep -q "KONDA-TODO\[ПРОВЕРИТЬ\] в C-исходнике похоже на двойной free" "$TMP/дф.конда" \
    || { echo "  ОШИБКА: double-free не помечен"; cat "$TMP/дф.конда"; exit 1; }
grep -qc "выделить(4)" "$TMP/дф.конда" \
    || { echo "  ОШИБКА: malloc не стал «выделить»"; exit 1; }
grep -vE "^\s*//" "$TMP/дф.конда" | grep -q "free(" \
    && { echo "  ОШИБКА: вызов free должен быть снят (autofree)"; exit 1; }
echo "  ок: лишний free снят, место помечено ПРОВЕРИТЬ, перевод компилируем"

echo "== по-настоящему непереводимое (&x во внешний scanf) =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/непереводимое.c" --без-проверки 2>/dev/null \
    | grep -q "KONDA-TODO\[НЕПЕРЕВОДИМО\]" \
    && echo "  ок: помечено KONDA-TODO[НЕПЕРЕВОДИМО]" \
    || { echo "  ОШИБКА: не помечено"; exit 1; }

if [ -x "$TRBIN" ]; then
    echo "== цикл проверки чинит то, что эвристика пропустила =="
    # «обёртка» не индексирует свой параметр → эвристика оставит сырой указатель,
    # но вызов передаёт массив. Цикл обязан поднять параметр до «срез<T>».
    python3 "$ROOT/kfc.py" "$ROOT/примеры/цикл_проверки.c" --без-проверки 2>/dev/null \
        | grep -q "обёртка(целое32\* a" \
        || { echo "  ОШИБКА: ожидался сырой указатель без цикла"; exit 1; }
    python3 "$ROOT/kfc.py" "$ROOT/примеры/цикл_проверки.c" -o "$TMP/ц.конда" 2>/dev/null
    grep -q "обёртка(срез<целое32> a" "$TMP/ц.конда" \
        && echo "  ок: цикл поднял параметр «обёртка» до «срез<целое32>»" \
        || { echo "  ОШИБКА: цикл не исправил параметр"; cat "$TMP/ц.конда"; exit 1; }
    check цикл_проверки "хвост=30"

    echo "== цикл проверки: вердикт «принят транспилятором» =="
    python3 "$ROOT/kfc.py" "$ROOT/примеры/указатели.c" -o "$TMP/у.конда" 2>&1 \
        | grep -q "принят транспилятором" \
        && echo "  ок: цикл подтвердил перевод у транспилятора" \
        || { echo "  ОШИБКА: цикл не подтвердил перевод"; exit 1; }

    echo "== вердикт честен: закомментированное меняет поведение =="
    python3 "$ROOT/kfc.py" "$ROOT/примеры/непереводимое.c" -o "$TMP/а.конда" \
        --отчёт "$TMP/а.json" 2>"$TMP/а.log" || true
    grep -q "поведение изменено" "$TMP/а.log" \
        && echo "  ок: не выдаём «принят», раз фрагмент закомментирован" \
        || { echo "  ОШИБКА: вердикт вводит в заблуждение"; cat "$TMP/а.log"; exit 1; }

    echo "== JSON-отчёт для ИИ =="
    python3 - "$TMP/а.json" <<'PY' || exit 1
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
assert d["всего"] >= 1, "ожидались задачи в отчёте"
assert d["блокирует_компиляцию"] >= 1, "ожидалась блокирующая задача"
z = d["задачи"][0]
for поле in ("файл", "строка", "категория", "код", "причина", "варианты",
             "c_исходник", "блокирует_компиляцию"):
    assert поле in z, f"нет поля {поле}"
assert z["варианты"], "у задачи должны быть варианты решения"
assert z["c_исходник"], "должен быть исходный код C"
print("  ок: отчёт содержит задачи с вариантами и C-исходником")
PY
fi

echo "== транзитивные ссылки: пересылка указателя вглубь =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/транзит.c" -o "$TMP/тр.конда" 2>"$TMP/тр.log"
grep -q "пометок: 0" "$TMP/тр.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/тр.log"; exit 1; }
grep -q "шагнуть(изменяемый целое32" "$TMP/тр.конда" \
    || { echo "  ОШИБКА: пересылочный параметр должен стать «изменяемый»"; exit 1; }
grep -q "прибавить(изменяемый целое32" "$TMP/тр.конда" \
    || { echo "  ОШИБКА: приёмник пересылки должен стать «изменяемый»"; exit 1; }
echo "  ок: цепочка «&х → шагнуть → прибавить» переведена в ссылки"
check транзит "итог=26"

echo "== NULL-указатели → «возможно<T*>» =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/нулевой.c" -o "$TMP/ну.конда" 2>"$TMP/ну.log"
grep -q "пометок: 0" "$TMP/ну.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/ну.log"; exit 1; }
grep -q "возможно<символ\*> выбрать" "$TMP/ну.конда" \
    || { echo "  ОШИБКА: возврат NULL должен дать «возможно<T*>»"; exit 1; }
grep -q "вернуть нуль" "$TMP/ну.конда" \
    || { echo "  ОШИБКА: NULL должен печататься как «нуль»"; exit 1; }
grep -q "== нуль" "$TMP/ну.конда" \
    || { echo "  ОШИБКА: «if (!p)» должен стать охранником «== нуль»"; exit 1; }
grep -q "небезопасно" "$TMP/ну.конда" \
    && { echo "  ОШИБКА: nullable-путь не должен требовать «небезопасно»"; exit 1; }
echo "  ок: возможно<T*>, «нуль» и охранники истинности на месте"
check нулевой "1:нашлось"

echo "== многофайловый проект: общий граф вызовов =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/мф_счёт.c" "$ROOT/примеры/мф_главный.c" \
    -o "$TMP/мфп" 2>"$TMP/мф.log"
grep -q "пометок: 0" "$TMP/мф.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/мф.log"; exit 1; }
grep -q "счёт_прибавить(изменяемый Счёт" "$TMP/мфп/мф_счёт.конда" \
    || { echo "  ОШИБКА: сигнатура из соседнего файла должна стать «изменяемый»"; exit 1; }
grep -q "счёт_прибавить(с, 7)" "$TMP/мфп/мф_главный.конда" \
    || { echo "  ОШИБКА: межфайловый вызов должен передавать голое имя"; exit 1; }
[ "$(cat "$TMP/мфп/"*.конда | grep -c "^структура Счёт")" = "1" ] \
    || { echo "  ОШИБКА: структура из заголовка должна эмититься один раз"; exit 1; }
echo "  ок: межфайловые «&с» переведены, структура из .h — один раз"
if [ -x "$TRBIN" ]; then
    cp "$TMP/мфп/мф_счёт.конда" "$TMP/мфп/мф_главный.конда" "$TR/"
    if ( cd "$TR" && ./Собранное/ТранспиляторКонда мф_счёт.конда мф_главный.конда \
            >/dev/null 2>&1 ); then
        out="$("$TR/вывод/мф_счёт.elf" 2>&1 || true)"
        rm -f "$TR/мф_счёт.конда" "$TR/мф_главный.конда"
        echo "$out" | grep -q "значение=12 шагов=2" \
            || { echo "  ОШИБКА вывода: $out"; exit 1; }
        echo "  ок: два .конда транспилированы вместе, вывод верен"
    else
        rm -f "$TR/мф_счёт.конда" "$TR/мф_главный.конда"
        echo "  ОШИБКА: многофайловый вывод не прошёл транспилятор"; exit 1
    fi
fi

echo "== внешние прототипы + memset-обнуление =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/библио.c" -o "$TMP/биб.конда" 2>"$TMP/биб.log"
grep -q "пометок: 0" "$TMP/биб.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/биб.log"; exit 1; }
grep -q "внешняя ничего сдвинуть_на(изменяемый целое32" "$TMP/биб.конда" \
    || { echo "  ОШИБКА: должен быть «внешняя …(изменяемый …)»-прототип"; exit 1; }
grep -q '#содержит "библио.h"' "$TMP/биб.конда" \
    || { echo "  ОШИБКА: заголовок библиотеки должен включаться"; exit 1; }
grep -q "с.битых = 0" "$TMP/биб.конда" \
    || { echo "  ОШИБКА: memset должен стать полевым обнулением"; exit 1; }
grep -q "memset" "$TMP/биб.конда" \
    && { echo "  ОШИБКА: сырой memset не должен остаться"; exit 1; }
echo "  ок: «&x» в библиотеку → внешняя+изменяемый; memset → поля"
if [ -x "$TRBIN" ]; then
    cp "$TMP/биб.конда" "$TR/_smoke_биб.конда"
    cp "$ROOT/примеры/библио.h" "$TR/"
    if ( cd "$TR" && ./Собранное/ТранспиляторКонда _smoke_биб.конда >/dev/null 2>&1 ); then
        out="$("$TR/вывод/_smoke_биб.elf" 2>&1 || true)"
        rm -f "$TR/_smoke_биб.конда" "$TR/библио.h"
        echo "$out" | grep -q "х=42 годных=42 битых=0 верх=5" \
            || { echo "  ОШИБКА вывода: $out"; exit 1; }
        echo "$out" | grep -q "сброшено=0" \
            || { echo "  ОШИБКА вывода: $out"; exit 1; }
        echo "  ок: транспилировано и запущено, мутация через границу C верна"
    else
        rm -f "$TR/_smoke_биб.конда" "$TR/библио.h"
        echo "  ОШИБКА: библио не прошло транспилятор"; exit 1
    fi
fi

echo "== доступ через анонимный union: «v.col[i].el[j]» без лишней точки =="
# clang вставляет неявный MemberExpr с пустым именем для анонимного union/struct.
# Регресс: kfc печатал «v..col[i]..el[j]». Проверяем только выражение доступа —
# сквозная транспиляция здесь невозможна: анонимные union в структуре сам язык
# Konda пока не поддерживает (отдельное ограничение, определение структуры не
# выражается), а исправление касается именно генерации цепочки доступа.
python3 "$ROOT/kfc.py" "$ROOT/примеры/аноним_союз.c" -o "$TMP/ас.конда" 2>/dev/null
grep -q "m.col\[i\].el\[j\] =" "$TMP/ас.конда" \
    || { echo "  ОШИБКА: доступ через анонимный union искажён"; grep "col" "$TMP/ас.конда"; exit 1; }
grep -q "\.\." "$TMP/ас.конда" \
    && { echo "  ОШИБКА: осталась лишняя точка (двойная «..»)"; grep "\.\." "$TMP/ас.конда"; exit 1; }
echo "  ок: анонимный член прозрачен, двойной точки нет"

echo "== точка входа: argc/argv + колбэк-регистрация =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/точка_входа.c" -o "$TMP/тв.конда" 2>"$TMP/тв.log"
grep -q "пометок: 0" "$TMP/тв.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/тв.log"; exit 1; }
# §36: сигнатура точки входа — единый срез; argc → длина(аргументы), argv → аргументы
grep -q "точка_входа(срез<символ\*> аргументы)" "$TMP/тв.конда" \
    || { echo "  ОШИБКА: сигнатура точки входа должна быть срез<символ*>"; exit 1; }
grep -q "целое32 счётчик = длина(аргументы)" "$TMP/тв.конда" \
    || { echo "  ОШИБКА: argc в теле должен стать длина(аргументы)"; exit 1; }
grep -q "настроить(счётчик)" "$TMP/тв.конда" \
    || { echo "  ОШИБКА: &счётчик должен стать изменяемый (без &)"; exit 1; }
grep -q "аргументы\[0\]" "$TMP/тв.конда" \
    || { echo "  ОШИБКА: argv[0] должен стать аргументы[0] (индексация среза)"; exit 1; }
# колбэк: имя функции в параметр-типфункции внешней
grep -q "внешняя ничего задать(Обработчик" "$TMP/тв.конда" \
    || { echo "  ОШИБКА: колбэк-параметр должен использовать типфункции"; exit 1; }
echo "  ок: argc→длина(аргументы), argv→аргументы (§36), колбэк через типфункции"
if [ -x "$TRBIN" ]; then
    cp "$TMP/тв.конда" "$TR/_smoke_тв.конда"
    cp "$ROOT/примеры/точка_вх.h" "$TR/"
    if ( cd "$TR" && ./Собранное/ТранспиляторКонда _smoke_тв.конда >/dev/null 2>&1 ); then
        out="$("$TR/вывод/_smoke_тв.elf" 2>&1 || true)"
        rm -f "$TR/_smoke_тв.конда" "$TR/точка_вх.h"
        echo "$out" | grep -q "событие 42" \
            || { echo "  ОШИБКА вывода: $out"; exit 1; }
        echo "$out" | grep -q "аргументов: 2" \
            || { echo "  ОШИБКА вывода: $out"; exit 1; }
        echo "  ок: транспилировано и запущено, argc-мутация и колбэк работают"
    else
        rm -f "$TR/_smoke_тв.конда" "$TR/точка_вх.h"
        echo "  ОШИБКА: точка_входа не прошло транспилятор"; exit 1
    fi
fi

echo "== перечисления: анонимный enum → конст, StaticAssert снят, локальный enum вынесен =="
python3 "$ROOT/kfc.py" "$ROOT/примеры/перечисления.c" -o "$TMP/пе.конда" 2>"$TMP/пе.log"
grep -q "пометок: 0" "$TMP/пе.log" \
    || { echo "  ОШИБКА: ожидался перевод без пометок"; cat "$TMP/пе.log"; exit 1; }
grep -q "конст целое32 КРАСНЫЙ = 0" "$TMP/пе.конда" \
    || { echo "  ОШИБКА: анонимный enum должен стать «конст» (авто-значение 0)"; exit 1; }
grep -q "конст целое32 СИНИЙ = 6" "$TMP/пе.конда" \
