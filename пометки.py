class Пометка:
    def __init__(self, код, строка_c=None, диагностика=None, деталь=None):
        рец = РЕЦЕПТЫ.get(код, {
            "категория": ПРОВЕРИТЬ, "заголовок": код,
            "причина": деталь or код, "варианты": [],
        })
        self.код = код
        self.категория = рец["категория"]
        self.заголовок = рец["заголовок"]
        self.причина = рец["причина"]
        self.деталь = деталь          # конкретика этого места (отдельной строкой)
        self.варианты = list(рец["варианты"])
        self.строка_c = строка_c          # исходная строка C (если известна)
        self.диагностика = диагностика    # текст ошибки транспилятора
        self.строка = 0                   # строка в .конда (проставляется при выводе)

    def блок(self, отступ=""):
        """Читаемый блок-комментарий для вставки в .конда."""
        л = [f"{отступ}// ┌─ KONDA-TODO[{self.категория}] {self.заголовок}"]
        for кусок in _перенос(f"ПРИЧИНА: {self.причина}", 72):
            л.append(f"{отступ}// │ {кусок}")
        if self.деталь:
            for кусок in _перенос(f"ЗДЕСЬ: {self.деталь}", 72):
                л.append(f"{отступ}// │ {кусок}")
        if self.строка_c:
            л.append(f"{отступ}// │ C-ИСХОДНИК: {self.строка_c}")
        if self.диагностика:
            л.append(f"{отступ}// │ ТРАНСПИЛЯТОР: {self.диагностика}")
        if self.варианты:
            л.append(f"{отступ}// │ ВАРИАНТЫ:")
            for i, в in enumerate(self.варианты, 1):
                перв = True
                for кусок in _перенос(в, 68):
                    л.append(f"{отступ}// │   {str(i) + ') ' if перв else '   '}{кусок}")
                    перв = False
        л.append(f"{отступ}// └─ после исправления удалите этот блок")
        return "\n".join(л)

    def словарь(self, файл):
        return {
            "файл": файл, "строка": self.строка, "категория": self.категория,
            "код": self.код, "заголовок": self.заголовок, "причина": self.причина,
            "c_исходник": self.строка_c, "деталь": self.деталь,
            "диагностика": self.диагностика,
            "варианты": self.варианты,
            "блокирует_компиляцию": self.категория in БЛОКИРУЮЩИЕ,
        }


def _перенос(текст, ширина):
    слова, строки, тек = текст.split(), [], ""
    for с in слова:
        if len(тек) + len(с) + 1 > ширина and тек:
            строки.append(тек)
            тек = с
        else:
            тек = f"{тек} {с}".strip()
    if тек:
        строки.append(тек)
    return строки or [""]


def отчёт_json(пометки, файл_c, файл_конда):
    блок = БЛОКИРУЮЩИЕ
    задачи = [п.словарь(файл_конда) for п in пометки]
    return json.dumps({
        "источник": файл_c,
        "результат": файл_конда,
        "всего": len(задачи),
        "блокирует_компиляцию": sum(1 for п in пометки if п.категория in блок),
        "по_категориям": {к: sum(1 for п in пометки if п.категория == к)
                          for к in (НЕПЕРЕВОДИМО, ОШИБКА, НЕБЕЗОПАСНО, ПРОВЕРИТЬ)},
        "задачи": задачи,
    }, ensure_ascii=False, indent=2)
