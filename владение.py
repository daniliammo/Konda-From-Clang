# -*- coding: utf-8 -*-
"""
Эвристика владения: C-параметр «T *p» + вызов «f(&x)» → Konda «изменяемый/вывод».

Зачем. В Konda нет оператора «&»: мутация переменной вызывающего выражается
модификаторами параметра — «изменяемый T x» (C# ref: чтение+запись) и
«вывод T x» (C# out: обязан быть присвоен по всем путям). Кодоген сам ставит
«*» в теле и «&» на вызове, поэтому программист их не пишет. Без этой эвристики
каждый «f(&x)» становился блокирующей пометкой — главным источником ручной
работы. С ней такой код переводится полностью автоматически и БЕЗОПАСНО
(ссылка не становится значением первого класса и не может повиснуть).

Что делаем:
  1. для каждой функции, ОПРЕДЕЛЁННОЙ в этом файле, смотрим на указательные
     параметры и классифицируем их использование в теле;
  2. смотрим на все вызовы этой функции в файле: передаётся ли всюду «&lvalue»;
  3. если да и параметр разыменовывается как одиночный объект — делаем его
     «вывод» (только пишут) либо «изменяемый» (читают/пишут);
  4. эмиттер печатает «p» вместо «*p»/«p[0]» в теле и «x» вместо «&x» на вызове.

Что НЕ трогаем (остаётся указателем/срезом — иначе смысл поплывёт):
  * параметр индексируется не только [0] → это массив → «срез<T>» (другой путь);
  * над параметром арифметика/инкремент → сырой указатель;
  * параметр возвращается («вернуть p») или от него берут адрес;
  * параметр сравнивается с NULL — это nullable, другой путь («возможно<T*>»);
  * хоть один вызов передаёт не «&переменная» и не параметр-ссылку вызывающего;
  * внешние функции (scanf и пр.) — их сигнатуру менять нельзя.

ТРАНЗИТИВНОСТЬ (фикспоинт). Проброс указателя дальше — «g(p)» внутри f — не
блокирует перевод, если параметр-приёмник g:j сам становится ссылкой: в Konda
проброс «изменяемый» → «изменяемый» легален, кодоген всё расставит. Условия
«все вызовы дают &lvalue ЛИБО параметр-ссылку вызывающего» и «все пересылки
ведут в параметры-ссылки» взаимно рекурсивны, поэтому решаются наибольшей
неподвижной точкой: оптимистично включаем всех кандидатов, затем вычёркиваем
нарушителей до стабилизации. Режим пересылочного параметра выводится из
режимов приёмников (все «вывод» → «вывод», иначе «изменяемый»); чистый цикл
пересылок без единого прямого чтения/записи остаётся указателем (нет основания).

Догадку «вывод vs изменяемый» проверяет и правит цикл проверки (проверка.py):
транспилятор точно скажет «выходной параметр не присвоен» или «изменяемый-
аргумент должен быть инициализирован».
"""

ИЗМЕНЯЕМЫЙ = "изменяемый"
ВЫВОД = "вывод"


class ТаблицаВладения:
    def __init__(self):
        self.режим = {}            # "функция:индекс" → «изменяемый» | «вывод»
        self.имена = {}            # имя функции → {имена ref/out-параметров}
        self.снятые_амперсанды = set()  # id узлов «&x», которые печатаем как «x»
        self.подстановки = {}      # функция → {имя локального указателя → узел цели}
        self.пропустить_объявления = set()  # id VarDecl'ов, которые не печатаем

    def режим_параметра(self, функция, индекс):
        return self.режим.get(f"{функция}:{индекс}")

    def ссылочные_имена(self, функция):
        return self.имена.get(функция, set())

    def подстановки_функции(self, функция):
        return self.подстановки.get(функция, {})


def _развернуть(n):
    while isinstance(n, dict) and n.get("kind") in (
            "ImplicitCastExpr", "ParenExpr", "ConstantExpr", "ExprWithCleanups"):
        вн = n.get("inner", [])
        if not вн:
            break
        n = вн[-1]
    return n


def _имя_ссылки(n):
    n = _развернуть(n)
    if isinstance(n, dict) and n.get("kind") == "DeclRefExpr":
        return (n.get("referencedDecl") or {}).get("name")
    return None


def _база_имя(n):
    """Имя переменной в основании выражения (сквозь касты/индекс/поле)."""
    n = _развернуть(n)
    if not isinstance(n, dict):
        return None
    k = n.get("kind")
    if k == "DeclRefExpr":
        return _имя_ссылки(n)
    вн = n.get("inner", [])
    if k in ("ArraySubscriptExpr", "MemberExpr") and вн:
        return _база_имя(вн[0])
    return None


def _это_нулевой_индекс(n):
    n = _развернуть(n)
    return isinstance(n, dict) and n.get("kind") == "IntegerLiteral" \
        and n.get("value") == "0"


def _цепочка_lvalue_ок(n):
    """lvalue-цепочка, выразимая ссылкой-проекцией Konda: поля/индексы с КОРНЕМ-
    ПЕРЕМЕННОЙ («s.f», «s->a.b», «arr[i]»). Транспилятор принимает такие в
    «изменяемый»/«вывод»/«чтение» (second-class reference; границы — при
    формировании ссылки). Отвергаем: корень-вызов (временное умерло бы до конца
    вызова — транспилятор это тоже отвергнет, но не надо и предлагать) и
    индексацию СЫРОГО указателя (в Konda она за «небезопасно»; массив C — можно:
    у него в qualType есть «[»)."""
    шагов = 0
    while isinstance(n, dict) and шагов < 32:
        шагов += 1
        k = n.get("kind")
        if k == "DeclRefExpr":
            return True
        if k == "MemberExpr":
            вн = n.get("inner") or []
            if not вн:
                return False
            n = _развернуть(вн[0])
            continue
        if k == "ArraySubscriptExpr":
            вн = n.get("inner") or []
            if len(вн) < 2:
                return False
            база = _развернуть(вн[0])
            qt = ""
            t = база.get("type") if isinstance(база, dict) else None
            if isinstance(t, dict):
                qt = t.get("qualType", "")
            if "[" not in qt:
                return False          # указатель, не массив → в Konda небезопасно
            n = база
            continue
        return False
    return False


def адрес_lvalue(арг):
    """«&lvalue-цепочка с корнем-переменной» («&x», «&s.f», «&s->a.b»,
    «&arr[i]») → узел «&», иначе None."""
    a = _развернуть(арг)
    if isinstance(a, dict) and a.get("kind") == "UnaryOperator" \
            and a.get("opcode") == "&":
        внутри = _развернуть((a.get("inner") or [{}])[0])
        if _цепочка_lvalue_ок(внутри):
            return a
    return None


def собрать_вызовы(декларации):
    """имя вызываемой функции → список (аргументы, имя вызывающей функции).
    Вызывающий нужен транзитивности: голое имя в аргументе допустимо, только
    если это параметр-ссылка именно ВЫЗЫВАЮЩЕЙ функции."""
    вызовы = {}

    def обход(n, вызывающий):
        if not isinstance(n, dict):
            return
        if n.get("kind") == "CallExpr":
            дети = n.get("inner", [])
            if дети:
                имя = _имя_ссылки(дети[0])
                if имя:
                    вызовы.setdefault(имя, []).append((дети[1:], вызывающий))
        for c in n.get("inner", []):
            обход(c, вызывающий)
    for д in декларации:
        имя_ф = д.get("name") if д.get("kind") == "FunctionDecl" else None
        обход(д, имя_ф)
    return вызовы


def _классифицировать(имя_п, тело):
    """Как используется указательный параметр «имя_п» в теле функции.
    → (категория, пересылки), где категория —
      «массив» | «арифметика» | «запись» | «чтение_запись» | «нет»,
    а пересылки — [(имя вызываемой, позиция аргумента)] для мест, где сам
    указатель уходит дальше голым именем: «g(p)». Судьбу пересылок решает
    фикспоинт в «проанализировать» (приёмник стал ссылкой → пересылка легальна)."""
    состояние = {"деref_чтение": 0, "деref_запись": 0,
                 "массив": False, "арифметика": False, "пересылки": []}

    def деref_узел(n):
        """Узел вида «*p» или «p[0]» для нашего параметра, иначе None."""
        if not isinstance(n, dict):
            return None
        k, оп = n.get("kind"), n.get("opcode")
        вн = n.get("inner", [])
        if k == "UnaryOperator" and оп == "*" and вн and _база_имя(вн[0]) == имя_п:
            return n
        if k == "ArraySubscriptExpr" and len(вн) >= 2 \
                and _база_имя(вн[0]) == имя_п and _это_нулевой_индекс(вн[1]):
            return n
        return None

    def стрелка_на_параметр(n):
        """«p->поле» — тоже разыменование p (доступ к полю объекта за ссылкой)."""
        return (isinstance(n, dict) and n.get("kind") == "MemberExpr"
                and n.get("isArrow")
                and _база_имя((n.get("inner") or [{}])[0]) == имя_п)

    def обход(n, родитель=None, позиция=0):
        if not isinstance(n, dict) or "kind" not in n:
            return
        k, оп = n.get("kind"), n.get("opcode")
        вн = n.get("inner", [])

        # p[i] с ненулевым/переменным индексом → это массив, не одиночный объект
        if k == "ArraySubscriptExpr" and len(вн) >= 2 \
                and _база_имя(вн[0]) == имя_п and not _это_нулевой_индекс(вн[1]):
            состояние["массив"] = True
        # p + n, p - n, p++/p-- → арифметика указателя. Именно САМ указатель:
        # «p->поле + n» и «p[0] + n» — это арифметика над значением, не над
        # указателем, поэтому сверяем прямую ссылку, а не основание выражения.
        if k == "BinaryOperator" and оп in ("+", "-"):
            for c in вн:
                if _имя_ссылки(c) == имя_п:
                    состояние["арифметика"] = True
        if k == "UnaryOperator" and оп in ("++", "--") and вн \
                and _имя_ссылки(вн[0]) == имя_п:
            состояние["арифметика"] = True
        # сам указатель уходит аргументом дальше: «g(p)». Если вызываемая
        # известна по имени — это пересылка (решит фикспоинт), иначе (вызов
        # по указателю на функцию) — блокер.
        if k == "CallExpr":
            имя_вызв = _имя_ссылки(вн[0]) if вн else None
            for i, а in enumerate(вн[1:]):
                if _имя_ссылки(а) == имя_п:
                    if имя_вызв:
                        состояние["пересылки"].append((имя_вызв, i))
                    else:
                        состояние["арифметика"] = True
        # переприсваивание самого указателя
        if k == "BinaryOperator" and оп == "=" and вн and _имя_ссылки(вн[0]) == имя_п:
            состояние["арифметика"] = True
        # «вернуть p» — ссылка не значение, вернуть её нельзя → блокер
        if k == "ReturnStmt" and вн and _имя_ссылки(вн[0]) == имя_п:
            состояние["арифметика"] = True
        # «&p» — адрес самого указателя → блокер
        if k == "UnaryOperator" and оп == "&" and вн and _имя_ссылки(вн[0]) == имя_п:
            состояние["арифметика"] = True
        # Сравнение параметра с NULL ссылку НЕ блокирует: все вызовы дают
        # «&переменная», значит NULL не приходит и проверка мертва — эмиттер
        # сворачивает её в константу («если (p == NULL)» → «если (ложь)»).

        # «p->поле» — разыменование p. Присваивание в ПОЛЕ не заполняет объект
        # целиком, поэтому «вывод» (обязан быть присвоен весь) не подходит —
        # считаем чтением, что даёт «изменяемый». Это и безопасно, и верно.
        if стрелка_на_параметр(n):
            состояние["деref_чтение"] += 1

        # чтение/запись через разыменование
        д = деref_узел(n)
        if д is not None:
            запись = (isinstance(родитель, dict)
                      and родитель.get("kind") in ("BinaryOperator",
                                                   "CompoundAssignOperator")
                      and родитель.get("opcode", "").endswith("=")
                      and родитель.get("opcode") not in ("==", "!=", "<=", ">=")
                      and позиция == 0)
            if запись:
                состояние["деref_запись"] += 1
                # «*p += x» читает тоже
                if родитель.get("kind") == "CompoundAssignOperator":
                    состояние["деref_чтение"] += 1
            else:
                состояние["деref_чтение"] += 1

        for i, c in enumerate(вн):
            обход(c, n, i)

    обход(тело)
    if состояние["массив"]:
        return "массив", []
    if состояние["арифметика"]:
        return "арифметика", []
    if состояние["деref_запись"] and not состояние["деref_чтение"]:
        return "запись", состояние["пересылки"]
    if состояние["деref_запись"] or состояние["деref_чтение"]:
        return "чтение_запись", состояние["пересылки"]
    return "нет", состояние["пересылки"]


def _узлы(n, вид, найдено=None):
    найдено = найдено if найдено is not None else []
    if isinstance(n, dict):
        if n.get("kind") == вид:
            найдено.append(n)
        for c in n.get("inner", []):
            _узлы(c, вид, найдено)
    return найдено


def _деref_базы(имя_п, n, найдено=None):
    """Узлы вида «*p», «p[0]», «p->поле» для указателя «имя_п»."""
    найдено = найдено if найдено is not None else []
    if isinstance(n, dict):
        k, оп = n.get("kind"), n.get("opcode")
        вн = n.get("inner", [])
        if k == "UnaryOperator" and оп == "*" and вн \
                and _имя_ссылки(вн[0]) == имя_п:
            найдено.append(n)
        elif k == "ArraySubscriptExpr" and len(вн) >= 2 \
                and _имя_ссылки(вн[0]) == имя_п and _это_нулевой_индекс(вн[1]):
            найдено.append(n)
        elif k == "MemberExpr" and n.get("isArrow") and вн \
                and _имя_ссылки(вн[0]) == имя_п:
            найдено.append(n)
        for c in вн:
            _деref_базы(имя_п, c, найдено)
    return найдено


def _число_ссылок(имя_п, n):
    return sum(1 for д in _узлы(n, "DeclRefExpr") if _имя_ссылки(д) == имя_п)


def _цель_подстановки(иниц):
    """Инициализатор «= &lvalue» → узел цели, если подстановка безопасна.

    Запрещаем цели с индексацией («&массив[и]»): индекс мог бы измениться между
    объявлением и использованием, и подстановка изменила бы смысл — указатель
    продолжал бы смотреть на СТАРЫЙ элемент, а подставленное выражение взяло бы
    новый. Простая переменная и «&структура.поле» этой проблемы не имеют."""
    адрес = адрес_lvalue(иниц)
    if адрес is None:
        return None
    цель = _развернуть((адрес.get("inner") or [{}])[0])
    if not isinstance(цель, dict) or цель.get("kind") not in (
            "DeclRefExpr", "MemberExpr"):
        return None
    if _узлы(цель, "ArraySubscriptExpr") or _узлы(цель, "CallExpr"):
        return None
    return цель


def _подстановки_функции(f, тело, qualtype, без_квалификаторов):
    """Локальные «T *p = &x;» → печатать «x» вместо «p», а объявление опустить.

    Условие безопасности: КАЖДОЕ упоминание «p» — разыменование («*p», «p[0]»,
    «p->поле»). Тогда «p» — просто другое имя для «x», и подстановка точно
    сохраняет смысл, включая алиасинг. Любое другое использование (переприсваивание
    «p = …», арифметика «p + 1», передача «f(p)», «вернуть p») означает, что
    указатель живёт своей жизнью — не подставляем."""
    подст, пропуск = {}, set()
    for d in _узлы(тело, "VarDecl"):
        имя_п = d.get("name")
        if not имя_п:
            continue
        qt = без_квалификаторов(qualtype(d))
        if qt.count("*") != 1 or "[" in qt:
            continue
        вн = [c for c in d.get("inner", []) if isinstance(c, dict) and "kind" in c]
        if not вн:
            continue
        цель = _цель_подстановки(вн[-1])
        if цель is None:
            continue
        # все ли упоминания «p» — разыменования?
        ссылок = _число_ссылок(имя_п, тело) - _число_ссылок(имя_п, d)
        дерефов = len(_деref_базы(имя_п, тело))
        if ссылок != дерефов:
            continue
        подст[имя_п] = цель
        if d.get("id"):
            пропуск.add(d["id"])
    return подст, пропуск


def проанализировать(декларации, qualtype, без_квалификаторов, политика=None,
                     исключённые=None):
    """Главный вход. → ТаблицаВладения. `политика.режим_ссылки` (от цикла
    проверки) переопределяет догадку, `политика.отмена_ссылки` — отменяет её.
    `исключённые` — имена функций, чьи сигнатуры трогать нельзя (например,
    одноимённые static-функции из разных файлов проекта)."""
    т = ТаблицаВладения()
    вызовы = собрать_вызовы(декларации)
    переопр = getattr(политика, "режим_ссылки", {}) if политика else {}
    отмена = getattr(политика, "отмена_ссылки", set()) if политика else set()
    исключённые = исключённые or set()

    # ── Фаза 1: собрать кандидатов (условия, не зависящие от других) ─────────
    канд = {}        # "ф:индекс" → описание кандидата
    парам_канд = {}  # (функция, имя параметра) → ключ кандидата
    for д in декларации:
        if д.get("kind") != "FunctionDecl":
            continue
        имя_ф = д.get("name")
        тело = next((c for c in д.get("inner", [])
                     if c.get("kind") == "CompoundStmt"), None)
        if тело is None:
            continue                       # прототип — нечего анализировать

        # Локальные «T *p = &x;» → подставляем «x», объявление опускаем.
        # Делаем и для main: там такие алиасы встречаются чаще всего.
        подст, пропуск = _подстановки_функции(д, тело, qualtype, без_квалификаторов)
        if подст:
            т.подстановки[имя_ф] = подст
            т.пропустить_объявления |= пропуск

        if имя_ф == "main" or имя_ф in исключённые:
            continue                       # сигнатуру трогать нельзя
        параметры = [c for c in д.get("inner", []) if c.get("kind") == "ParmVarDecl"]
        for i, п in enumerate(параметры):
            ключ = f"{имя_ф}:{i}"
            if ключ in отмена:
                continue                   # цикл проверки отменил ссылку
            qt = без_квалификаторов(qualtype(п))
            if qt.count("*") != 1 or "[" in qt:
                continue                   # только одиночный «T *», не «T **»
            if qt.replace("*", "").strip() in ("void", "char"):
                continue                   # void* — неизвестный тип; char* — строка
            имя_п = п.get("name")
            if not имя_п:
                continue
            кат, пересылки = _классифицировать(имя_п, тело)
            if кат in ("массив", "арифметика"):
                continue                   # массив → путь среза; арифметика → сырой
            if кат == "нет" and not пересылки:
                continue                   # параметр не используется — не трогаем
            канд[ключ] = {"функция": имя_ф, "индекс": i, "имя": имя_п,
                          "кат": кат, "пересылки": пересылки, "режим": None}
            парам_канд[(имя_ф, имя_п)] = ключ

    # ── Фаза 2: наибольшая неподвижная точка ─────────────────────────────────
    # Условия кандидата взаимно рекурсивны (вызов может передавать параметр-
    # ссылку ВЫЗЫВАЮЩЕГО; пересылка легальна, если ссылкой стал ПРИЁМНИК),
    # поэтому: оптимистично считаем всех годными и вычёркиваем нарушителей,
    # пока список не стабилизируется. Затем выводим режимы (тоже фикспоинт) и
    # вычёркиваем кандидатов без основания (чистый цикл пересылок).
    изменилось = True
    while изменилось:
        изменилось = False
        # 2а. вычёркивание нарушителей
        нестабильно = True
        while нестабильно:
            нестабильно = False
            for ключ in list(канд):
                к = канд[ключ]
                годен = all(f"{цф}:{ци}" in канд for цф, ци in к["пересылки"])
                if годен:
                    for арги, вызывающий in вызовы.get(к["функция"], []):
                        if len(арги) <= к["индекс"]:
                            continue
                        а = арги[к["индекс"]]
                        if адрес_lvalue(а):
                            continue
                        имя_а = _имя_ссылки(а)
                        ак = парам_канд.get((вызывающий, имя_а)) if имя_а else None
                        if ак is not None and ак in канд:
                            continue       # голый параметр-ссылка вызывающего
                        годен = False
                        break
                if not годен:
                    del канд[ключ]
                    нестабильно = True
        # 2б. режимы: прямое использование задаёт базу, пересылки уточняют.
        # «вывод» только если ВСЕ источники — запись; любое чтение (своё или
        # у приёмника-«изменяемый») → «изменяемый».
        for к in канд.values():
            к["режим"] = {"запись": ВЫВОД, "чтение_запись": ИЗМЕНЯЕМЫЙ}.get(к["кат"])
        менялись_режимы = True
        while менялись_режимы:
            менялись_режимы = False
            for к in канд.values():
                if к["режим"] == ИЗМЕНЯЕМЫЙ:
                    continue
                новый = к["режим"]
                for цф, ци in к["пересылки"]:
                    цр = канд[f"{цф}:{ци}"]["режим"]
                    if цр == ИЗМЕНЯЕМЫЙ:
                        новый = ИЗМЕНЯЕМЫЙ
                    elif цр == ВЫВОД and новый is None:
                        новый = ВЫВОД
                if новый != к["режим"]:
                    к["режим"] = новый
                    менялись_режимы = True
        # 2в. без основания (цикл пересылок без единого чтения/записи) — убрать;
        # удаление может сломать чужие пересылки → внешний цикл повторит 2а.
        for ключ in [кл for кл, к in канд.items() if к["режим"] is None]:
            del канд[ключ]
            изменилось = True

    # ── Фаза 3: заполнить таблицу ────────────────────────────────────────────
    for ключ, к in канд.items():
        т.режим[ключ] = переопр.get(ключ) or к["режим"]
        т.имена.setdefault(к["функция"], set()).add(к["имя"])
        for арги, _вызывающий in вызовы.get(к["функция"], []):
            if len(арги) > к["индекс"]:
                a = адрес_lvalue(арги[к["индекс"]])
                if a is not None and a.get("id"):
                    т.снятые_амперсанды.add(a["id"])
    return т
